// Generates TWEAKS.md from the tweak catalog so the documentation can never drift from the code.
// Usage: dotnet run --project tools/Frtune.DocGen > TWEAKS.md
using System.Text;
using Frtune.Core.Engine;
using Frtune.Core.Model;
using Frtune.Core.Tweaks.Catalog;

var sb = new StringBuilder();
sb.AppendLine("# Tweak reference");
sb.AppendLine();
sb.AppendLine("<!-- Generated by tools/Frtune.DocGen. Do not edit by hand: run `dotnet run --project tools/Frtune.DocGen > TWEAKS.md`. -->");
sb.AppendLine();
sb.AppendLine($"Every tweak frtune can apply ({TweakCatalog.All.Count} in total), grouped by page, with the exact registry values, services, scheduled tasks, power settings or commands it touches.");
sb.AppendLine("Before applying, frtune saves the current value of every target listed here, and turning a tweak off writes those saved values back.");
sb.AppendLine();
sb.AppendLine("Risk: **Safe** = no known downside · **Moderate** = has a trade-off, read the description · **Advanced** = security or stability trade-off, never part of a preset, asks for confirmation.");
sb.AppendLine();
sb.AppendLine("Presets: " + string.Join(" · ", Presets.All.Select(p => $"**{p.Name}**")));
sb.AppendLine();

foreach (var group in TweakCatalog.All.GroupBy(t => t.Category))
{
    sb.AppendLine($"## {group.Key}");
    sb.AppendLine();
    foreach (var t in group)
    {
        sb.AppendLine($"### {t.Name}");
        sb.AppendLine();
        sb.AppendLine($"`{t.Id}` · **{t.Risk}**" +
            (t.Restart != RestartKind.None ? $" · needs: {t.Restart}" : "") +
            (t.Presets != Preset.None ? $" · presets: {t.Presets}" : "") +
            (t.ApplicabilityNote is not null ? $" · only: {t.ApplicabilityNote}" : ""));
        sb.AppendLine();
        sb.AppendLine(t.Description);
        sb.AppendLine();
        if (t.Warning is not null)
        {
            sb.AppendLine($"> **Warning:** {t.Warning}");
            sb.AppendLine();
        }
        foreach (var c in t.StaticChanges) sb.AppendLine($"- `{c.Describe().Replace("`", "'")}`");
        if (t.HasDynamicChanges) sb.AppendLine("- Plus one entry per network adapter found on the PC (see description).");
        sb.AppendLine();
    }
}
Console.Out.Write(sb.ToString().Replace("\r\n", "\n"));
